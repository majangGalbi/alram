def test_month_and_year_rollover():
    nye = datetime(2026, 12, 31, 23, 50)
    assert parse_time("20분 뒤", nye) == dt(2027, 1, 1, 0, 10)
    assert parse_time("내일 9시", nye) == dt(2027, 1, 1, 9, 0)
    assert parse_time("5일 오후 3시", nye) == dt(2027, 1, 5, 15, 0)
    assert parse_time("1월 2일 9시", nye) == dt(2027, 1, 2, 9, 0)
    assert parse_time("자정", nye) == dt(2027, 1, 1, 0, 0)


def test_day_of_month_missing_in_next_month():
    jan31 = datetime(2027, 1, 31, 12, 0)
    with pytest.raises(TimeParseError):
        parse_time("30일 3시", jan31)  # 1월 30일 지남 → 2월 30일은 없음


def test_leap_day():
    assert parse_time("2028-02-29 09:00", BASE) == dt(2028, 2, 29, 9, 0)


def test_weekday_from_sunday():
    sunday = datetime(2026, 11, 8, 10, 0)
    assert parse_time("월요일 9시", sunday) == dt(2026, 11, 9, 9, 0)
    assert parse_time("다음주 월요일 9시", sunday) == dt(2026, 11, 9, 9, 0)  # 월요일 시작 주 기준
    assert parse_time("이번주 일요일 오후 3시", sunday) == dt(2026, 11, 8, 15, 0)
    assert parse_time("일요일 오전 9시", sunday) == dt(2026, 11, 15, 9, 0)


def test_timezone_aware_base_uses_wall_clock():
    seoul = pytz.timezone("Asia/Seoul")
    aware = seoul.localize(BASE)
    result = parse_time("30분 뒤", aware)
    assert result.tzinfo is None
    assert result == dt(2026, 11, 5, 14, 30)


def test_microseconds_are_dropped():
    base = BASE.replace(second=12, microsecond=345678)
    assert parse_time("10분 뒤", base) == dt(2026, 11, 5, 14, 10, 12)


def test_relative_keeps_seconds():
    base = BASE.replace(second=42)
    assert parse_time("1시간 뒤", base) - base == timedelta(hours=1)


def test_compat_wrapper_returns_datetime():
    assert parse_korean_time("내일 오후 3시", BASE) == dt(2026, 11, 6, 15, 0)


