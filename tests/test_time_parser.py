@pytest.mark.parametrize(
    "text,expected",
    [
        ("오늘 오전 9시", dt(2026, 11, 5, 9, 0)),       # 명시한 '오늘' → 넘기지 않음
        ("오늘 1시", dt(2026, 11, 5, 13, 0)),          # 01시/13시 모두 지남 → 그대로
        ("오늘 13:00", dt(2026, 11, 5, 13, 0)),
        ("어제 3시", dt(2026, 11, 4, 15, 0)),
        ("yesterday 3pm", dt(2026, 11, 4, 15, 0)),
        ("2025년 1월 1일 9시", dt(2025, 1, 1, 9, 0)),
        ("이번주 월요일 9시", dt(2026, 11, 2, 9, 0)),
        ("이번달 3일 3시", dt(2026, 11, 3, 15, 0)),
    ],
)
def test_explicit_past_is_returned_as_is(text, expected):
    """날짜를 명시했는데 지난 시각이면 넘기지 않고 그대로 돌려준다 (호출부가 거절)."""
    result = parse_time(text, BASE)
    assert result == expected
    assert result < BASE


