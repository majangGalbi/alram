def test_nearest_future_ambiguous_hour():
    morning = datetime(2026, 11, 5, 8, 0)
    assert parse_time("9시", morning) == dt(2026, 11, 5, 9, 0)
    assert parse_time("7시", morning) == dt(2026, 11, 5, 19, 0)
    assert parse_time("오늘 7시", morning) == dt(2026, 11, 5, 19, 0)
    late = datetime(2026, 11, 5, 23, 30)
    assert parse_time("9시", late) == dt(2026, 11, 6, 9, 0)
    assert parse_time("오늘 9시", late) == dt(2026, 11, 5, 21, 0)


